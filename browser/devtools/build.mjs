#!/usr/bin/env node
/**
 * Vendors the shared matcher into the extension.
 *
 * `engine/src/dom-match.ts` is the one answer to "does this rule reach anything
 * on screen". The overlay gets it from the server it is served by; an extension
 * has no server, and may not fetch code at runtime — Manifest V3 prohibits
 * remote code, and an extension that evaluated a script it downloaded would be
 * rejected from the store and would be right to be.
 *
 * So the extension carries a copy, generated from that constant and committed,
 * and `--check` is what CI runs to reject one that has drifted. Same arrangement
 * as `engine/dist/loupe.mjs`, for the same reason: the alternative is a build
 * step nobody runs and a vendored file that is quietly a version behind.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MATCH_JS, MATCH_VERSION } from '../../engine/src/dom-match.ts';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, 'vendor', 'match.js');
const check = process.argv.includes('--check');

// A JSON string, not a template literal: the matcher's own source contains
// backticks and `${`, and the point of this file is to hand it over unaltered.
const next = `// Generated by \`node browser/devtools/build.mjs\` from engine/src/dom-match.ts — do not edit.
// Matcher version ${MATCH_VERSION}.
//
// The panel and the sidebar evaluate this string in the inspected page. It is
// bundled, never fetched: see the note in build.mjs.
globalThis.LOUPE_MATCH_SRC = ${JSON.stringify(MATCH_JS)};
globalThis.LOUPE_MATCH_VERSION = ${MATCH_VERSION};
`;

if (check) {
	const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
	if (current === next) {
		process.stdout.write('browser/devtools/vendor/match.js is up to date with engine/src/dom-match.ts\n');
		process.exit(0);
	}
	process.stderr.write(
		current === null
			? 'browser/devtools/vendor/match.js is missing. Run `node browser/devtools/build.mjs` and commit it.\n'
			: 'browser/devtools/vendor/match.js is stale — engine/src/dom-match.ts has changed since it was generated.\n  Run `node browser/devtools/build.mjs` and commit the result.\n',
	);
	process.exit(1);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, next);
process.stdout.write(`vendor/match.js  ${(Buffer.byteLength(next) / 1024).toFixed(1)} KB\n`);
