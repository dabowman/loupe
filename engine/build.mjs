#!/usr/bin/env node
/**
 * Bundles the engine into `dist/loupe.mjs`, dependencies and all.
 *
 * The bundle is committed. Nothing in a Claude Code marketplace install runs
 * `npm install` on a plugin's behalf, so an engine that imports `picomatch` at
 * load time is an engine that throws on every hook run for anyone who installed
 * this the normal way. Committing the built artifact is the cost of being
 * installable without a toolchain.
 *
 * Two things keep the artifact honest rather than a second source of truth:
 * `bin/loupe.mjs` prefers `src/` wherever the deps are installed, so a checkout
 * someone is editing never runs the bundle; and `--check` re-bundles and
 * compares, which is what CI runs to reject a commit whose `dist/` no longer
 * matches its `src/`.
 *
 * `dist/` deliberately sits at the same depth as `src/`: the engine resolves the
 * preset directory and the plugin manifest relative to `import.meta.url`, and
 * equal depth is what makes those land in the same place from either entry.
 */

import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, 'dist', 'loupe.mjs');
const check = process.argv.includes('--check');

const pkg = JSON.parse(readFileSync(join(HERE, 'package.json'), 'utf8'));

// postcss ships CommonJS. esbuild's ESM output stubs `require` with a shim that
// throws on node builtins, so postcss dies on its own `require('path')` before
// the first file is read. Handing the bundle a real `createRequire` is what lets
// a CJS dependency keep behaving like one inside an ES module.
const banner = [
	'// Generated by `npm run build` from src/ — do not edit.',
	`// loupe ${pkg.version}`,
	"import { createRequire as __loupeCreateRequire } from 'node:module';",
	'const require = __loupeCreateRequire(import.meta.url);',
].join('\n');

const result = await build({
	entryPoints: [join(HERE, 'src', 'cli.mjs')],
	bundle: true,
	platform: 'node',
	format: 'esm',
	target: 'node18',
	write: false,
	banner: { js: `#!/usr/bin/env node\n${banner}` },
	// Preset JSON is read from disk at runtime, not imported, so it stays
	// alongside the bundle rather than inside it — `loupe presets` lists what is
	// in that directory, and a preset you can read is a preset you can copy.
	external: ['postcss-sass', 'postcss-styl'],
	logOverride: {
		// `import(pkg)` in syntax.mjs is deliberately unresolvable: the two
		// syntaxes not shipped as deps are left for the host to provide.
		'unsupported-dynamic-import': 'silent',
	},
	legalComments: 'none',
});

const next = result.outputFiles[0].text;

if (check) {
	const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
	if (current === next) {
		process.stdout.write('dist/loupe.mjs is up to date with src/\n');
		process.exit(0);
	}
	process.stderr.write(
		current === null
			? 'dist/loupe.mjs is missing. Run `npm run build` and commit it.\n'
			: 'dist/loupe.mjs is stale — src/ has changed since it was built.\n  Run `npm run build` and commit the result.\n',
	);
	process.exit(1);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, next);
process.stdout.write(`dist/loupe.mjs  ${(Buffer.byteLength(next) / 1024).toFixed(0)} KB\n`);
