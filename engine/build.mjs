#!/usr/bin/env node
/**
 * Bundles the engine into `dist/loupe.mjs`, dependencies and all.
 *
 * The bundle is committed, because nothing in a Claude Code marketplace install
 * runs `npm install` on a plugin's behalf. `bin/loupe.mjs` prefers `src/`
 * wherever the dev toolchain is installed, and `--check` re-bundles and compares
 * — which is what CI runs to reject a `dist/` that no longer matches its `src/`.
 *
 * esbuild strips types, it does not check them; type checking is `npm run
 * typecheck`, and both run in CI.
 *
 * `dist/` deliberately sits at the same depth as `src/`, so the engine's
 * `import.meta.url` lookups land in the same place from either entry.
 *
 * Design notes: docs/design/cli.md#building-and-distribution
 */

import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, 'dist', 'loupe.mjs');
const check = process.argv.includes('--check');

const pkg = JSON.parse(readFileSync(join(HERE, 'package.json'), 'utf8'));

// postcss ships CommonJS, and esbuild's ESM output stubs `require` with a shim
// that throws on node builtins. A real `createRequire` is what lets a CJS
// dependency keep behaving like one inside an ES module.
const banner = [
	'// Generated by `npm run build` from src/ — do not edit.',
	`// loupe ${pkg.version}`,
	"import { createRequire as __loupeCreateRequire } from 'node:module';",
	'const require = __loupeCreateRequire(import.meta.url);',
].join('\n');

const result = await build({
	entryPoints: [join(HERE, 'src', 'cli.ts')],
	bundle: true,
	platform: 'node',
	format: 'esm',
	target: 'node18',
	write: false,
	banner: { js: `#!/usr/bin/env node\n${banner}` },
	logOverride: {
		// `import(pkg)` in syntax.ts is deliberately unresolvable: the two syntaxes
		// not shipped as deps are left for the host to provide.
		'unsupported-dynamic-import': 'silent',
	},
	legalComments: 'none',
});

const [output] = result.outputFiles;
if (!output) {
	process.stderr.write('esbuild produced no output.\n');
	process.exit(1);
}
const next = output.text;

if (check) {
	const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : null;
	if (current === next) {
		process.stdout.write('dist/loupe.mjs is up to date with src/\n');
		process.exit(0);
	}
	process.stderr.write(
		current === null
			? 'dist/loupe.mjs is missing. Run `npm run build` and commit it.\n'
			: 'dist/loupe.mjs is stale — src/ has changed since it was built.\n  Run `npm run build` and commit the result.\n',
	);
	process.exit(1);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, next);
process.stdout.write(`dist/loupe.mjs  ${(Buffer.byteLength(next) / 1024).toFixed(0)} KB\n`);
